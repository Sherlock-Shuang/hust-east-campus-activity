import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createLiveServer} from '../server/index.mjs';
import {LEARNING_BOARD} from '../src/activity-catalog.js';
const PASSWORD='learning-request-test-password';

test('Node learning messages require audience/CSRF, remain private, reach the admin, and persist across restart',async t=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'campus-learning-'));let now=100000;
  let app=await createLiveServer({rootDir:root,password:PASSWORD,now:()=>now});
  await app.listen(0);let origin=`http://127.0.0.1:${app.server.address().port}`;
  t.after(async()=>{await app.close();await rm(root,{recursive:true,force:true});});
  const request=(url,options={})=>fetch(origin+url,{...options,headers:{Origin:origin,'Content-Type':'application/json',...options.headers}});
  const join=async nickname=>{const response=await request('/api/audience/join',{method:'POST',body:JSON.stringify({nickname,tabId:'one'})});assert.equal(response.status,200);return {cookie:response.headers.get('set-cookie').split(';')[0],...await response.json()};};
  const login=async()=>{const response=await request('/api/admin/login',{method:'POST',body:JSON.stringify({password:PASSWORD})});assert.equal(response.status,200);return {cookie:response.headers.get('set-cookie').split(';')[0],...await response.json()};};
  const event={type:'learning_request',eventId:'wish-one',tabId:'one',text:'  我想学自动整理文件\n还有剪视频  ',position:{x:LEARNING_BOARD.x,y:LEARNING_BOARD.y,z:LEARNING_BOARD.z}};
  const post=(viewer,body=event,headers={})=>request('/api/audience/events',{method:'POST',headers:{Cookie:viewer.cookie,'X-CSRF-Token':viewer.csrfToken,...headers},body:JSON.stringify(body)});
  assert.equal((await request('/api/audience/learning-requests')).status,401);
  assert.equal((await request('/api/admin/learning-requests')).status,401);
  const viewer=await join('学习者'),other=await join('旁观者'),admin=await login();
  assert.equal((await request('/api/admin/learning-requests',{headers:{Cookie:viewer.cookie}})).status,401);
  assert.equal((await post(viewer,event,{'X-CSRF-Token':''})).status,403);
  assert.equal((await post(viewer,event,{Origin:'https://elsewhere.invalid'})).status,403);
  assert.equal((await post(viewer,{...event,text:' '})).status,400);
  assert.equal((await post(viewer,{...event,position:{...event.position,x:LEARNING_BOARD.x+100}})).status,403);
  assert.equal((await post(viewer)).status,200);
  assert.equal((await (await post(viewer)).json()).duplicate,true);
  const own=await (await request('/api/audience/learning-requests',{headers:{Cookie:viewer.cookie}})).json();
  assert.deepEqual(own.messages,[{id:'wish-one',text:'我想学自动整理文件\n还有剪视频',createdAt:now}]);
  assert.deepEqual(await (await request(`/api/audience/learning-requests?audienceId=${viewer.audience.id}`,{headers:{Cookie:other.cookie}})).json(),{messages:[]});
  const listed=await (await request('/api/admin/learning-requests?q='+encodeURIComponent('整理'),{headers:{Cookie:admin.cookie}})).json();
  assert.equal(listed.total,1);assert.equal(listed.participants,1);assert.equal(listed.messages[0].nickname,'学习者');assert.ok(!JSON.stringify(listed).includes('identityHash'));
  const none=await (await request('/api/admin/learning-requests?q=unknown',{headers:{Cookie:admin.cookie}})).json();assert.equal(none.total,1);assert.equal(none.messages.length,0);
  await app.close();app=await createLiveServer({rootDir:root,password:PASSWORD,now:()=>now});await app.listen(0);origin=`http://127.0.0.1:${app.server.address().port}`;
  assert.deepEqual(await (await request('/api/audience/learning-requests',{headers:{Cookie:viewer.cookie}})).json(),own);
  assert.equal((await (await post(viewer)).json()).duplicate,true);
  const newAdmin=await login(),state=app.getState();
  const saved=await request('/api/admin/state',{method:'PUT',headers:{Cookie:newAdmin.cookie,'X-CSRF-Token':newAdmin.csrfToken},body:JSON.stringify({state:{...state,paused:true},expectedRevision:state.revision})});assert.equal(saved.status,200);
  now+=6000;assert.equal((await post(viewer,{...event,eventId:'paused-wish'})).status,409);
  assert.equal(app.getAudienceData().audiences[viewer.audience.id].learningRequests.length,1);
});
